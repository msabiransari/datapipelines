package co.datapipelines.web.ui

import com.fasterxml.jackson.databind.ObjectMapper
import io.kotest.assertions.withClue
import io.kotest.matchers.collections.shouldHaveSize
import io.kotest.matchers.collections.shouldNotBeEmpty
import io.kotest.matchers.shouldBe
import io.kotest.matchers.string.shouldContain
import io.kotest.matchers.string.shouldNotContain
import org.junit.jupiter.api.Test

/** Audits the generated classpath resource against the real manifest and upstream licence bytes. */
class VendoredNoticesAuditTest {
    private val firstParty = setOf("design-system", "datapipelines-dashboard-runtime")

    @Test
    fun `every third-party block has one inventory row and its exact licence section`() {
        val manifest = ObjectMapper().readTree(resource("vendor/design-system/vendor-manifest.json"))
        val notices = resource("vendor/THIRD-PARTY-NOTICES.txt")
        val blocks = manifest.properties().filter { it.key !in firstParty }.sortedBy { it.key }
        // A removed or unread manifest must never make the audit vacuously green.
        blocks.shouldNotBeEmpty()
        val sections = notices.split(Regex("(?m)^===== ")).drop(1)
        sections shouldHaveSize blocks.size
        blocks.zip(sections).forEach { (entry, section) ->
            val name = entry.key
            val block = entry.value
            val id = block.get("license").asText()
            val label = block.get("package")?.asText() ?: name
            val row = "$name — $label ${block.get("version").asText()} — $id — ${block.get("source").asText()}"
            withClue(name) {
                notices.lines().count { it == row } shouldBe 1
                section.substringBefore('\n') shouldBe "$name ($id) ====="
                section.substringAfter('\n').trim() shouldBe
                    resource(block.get("license_file").asText()).replace("\r\n", "\n").trim()
            }
        }
        firstParty.forEach { notices shouldNotContain "===== $it (" }
    }

    @Test
    fun `header identifies the generator scope and own code without a timestamp`() {
        val header = resource("vendor/THIRD-PARTY-NOTICES.txt").substringBefore("\n\n")
        header shouldContain "Product code: AGPL-3.0 (see LICENSE)."
        header shouldContain "Generated by :modules:web:generateVendoredAssetNotices; do not edit."
        header shouldContain "Scope: third-party browser-asset blocks in vendor/design-system/vendor-manifest.json."
        header shouldContain "Own code (no third-party licence requirement): ${firstParty.sorted().joinToString(", ")}"
        Regex("\\d{4}-\\d{2}-\\d{2}|\\d{2}:\\d{2}:\\d{2}").containsMatchIn(header) shouldBe false
    }

    private fun resource(path: String): String =
        requireNotNull(javaClass.classLoader.getResourceAsStream("static/$path")) { "Missing classpath asset: $path" }
            .bufferedReader(Charsets.UTF_8)
            .use { it.readText() }
}
