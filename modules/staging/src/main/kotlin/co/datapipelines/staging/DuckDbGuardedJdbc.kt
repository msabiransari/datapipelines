package co.datapipelines.staging

import java.sql.CallableStatement
import java.sql.Connection
import java.sql.DatabaseMetaData
import java.sql.PreparedStatement
import java.sql.ResultSet
import java.sql.SQLException
import java.sql.SQLFeatureNotSupportedException
import java.sql.Statement

/*
 * The JDBC decorators an author lease of a DuckDB staging database is handed (staging.md §8.5):
 * every method that turns SQL text into execution passes the text through [DuckDbAuthorSqlGate]
 * first, and nothing reachable from the decorated connection yields the undecorated one.
 *
 * Scope, stated honestly: the author controls SQL TEXT, never JDBC calls. These decorators make
 * the gate unskippable for every path the executor uses to run that text — `createStatement`,
 * `prepareStatement` (which on DuckDB executes the leading statements of multi-statement text at
 * prepare time, probe 10), the statement-level `execute*` and `addBatch` — and refuse the two exits
 * a DP code path could take to the raw driver: `unwrap` and `prepareCall`. A `ResultSet`'s
 * `getStatement()` still returns the driver's statement; reaching it needs DP code, not author SQL.
 */

/** The author's view of a leased DuckDB connection: gated text, no route to the raw driver. */
internal class GuardedConnection(
    private val delegate: Connection,
) : Connection by delegate {
    override fun createStatement(): Statement = GuardedStatement(delegate.createStatement(), this)

    override fun createStatement(
        resultSetType: Int,
        resultSetConcurrency: Int,
    ): Statement = GuardedStatement(delegate.createStatement(resultSetType, resultSetConcurrency), this)

    override fun createStatement(
        resultSetType: Int,
        resultSetConcurrency: Int,
        resultSetHoldability: Int,
    ): Statement = GuardedStatement(delegate.createStatement(resultSetType, resultSetConcurrency, resultSetHoldability), this)

    override fun prepareStatement(sql: String): PreparedStatement = gated(sql) { delegate.prepareStatement(sql) }

    override fun prepareStatement(
        sql: String,
        autoGeneratedKeys: Int,
    ): PreparedStatement = gated(sql) { delegate.prepareStatement(sql, autoGeneratedKeys) }

    override fun prepareStatement(
        sql: String,
        columnIndexes: IntArray,
    ): PreparedStatement = gated(sql) { delegate.prepareStatement(sql, columnIndexes) }

    override fun prepareStatement(
        sql: String,
        columnNames: Array<out String>,
    ): PreparedStatement = gated(sql) { delegate.prepareStatement(sql, columnNames) }

    override fun prepareStatement(
        sql: String,
        resultSetType: Int,
        resultSetConcurrency: Int,
    ): PreparedStatement = gated(sql) { delegate.prepareStatement(sql, resultSetType, resultSetConcurrency) }

    override fun prepareStatement(
        sql: String,
        resultSetType: Int,
        resultSetConcurrency: Int,
        resultSetHoldability: Int,
    ): PreparedStatement = gated(sql) { delegate.prepareStatement(sql, resultSetType, resultSetConcurrency, resultSetHoldability) }

    override fun prepareCall(sql: String): CallableStatement = throw callableRefused()

    override fun prepareCall(
        sql: String,
        resultSetType: Int,
        resultSetConcurrency: Int,
    ): CallableStatement = throw callableRefused()

    override fun prepareCall(
        sql: String,
        resultSetType: Int,
        resultSetConcurrency: Int,
        resultSetHoldability: Int,
    ): CallableStatement = throw callableRefused()

    override fun getMetaData(): DatabaseMetaData = GuardedMetaData(delegate.metaData, this)

    override fun <T : Any?> unwrap(iface: Class<T>): T =
        if (iface.isInstance(this)) iface.cast(this) else throw SQLException("a DuckDB staging author connection does not unwrap")

    override fun isWrapperFor(iface: Class<*>): Boolean = iface.isInstance(this)

    private inline fun gated(
        sql: String,
        prepare: () -> PreparedStatement,
    ): PreparedStatement {
        DuckDbAuthorSqlGate.check(sql)
        return GuardedPreparedStatement(prepare(), this)
    }

    private fun callableRefused() = SQLFeatureNotSupportedException("DuckDB staging has no callable statements")
}

/** A statement whose every SQL-text entry point is gated; `getConnection()` is the guarded connection. */
internal class GuardedStatement(
    private val delegate: Statement,
    private val connection: Connection,
) : Statement by delegate {
    override fun execute(sql: String): Boolean = gate(sql).let { delegate.execute(sql) }

    override fun execute(
        sql: String,
        autoGeneratedKeys: Int,
    ): Boolean = gate(sql).let { delegate.execute(sql, autoGeneratedKeys) }

    override fun execute(
        sql: String,
        columnIndexes: IntArray,
    ): Boolean = gate(sql).let { delegate.execute(sql, columnIndexes) }

    override fun execute(
        sql: String,
        columnNames: Array<out String>,
    ): Boolean = gate(sql).let { delegate.execute(sql, columnNames) }

    override fun executeQuery(sql: String): ResultSet = gate(sql).let { delegate.executeQuery(sql) }

    override fun executeUpdate(sql: String): Int = gate(sql).let { delegate.executeUpdate(sql) }

    override fun executeUpdate(
        sql: String,
        autoGeneratedKeys: Int,
    ): Int = gate(sql).let { delegate.executeUpdate(sql, autoGeneratedKeys) }

    override fun executeUpdate(
        sql: String,
        columnIndexes: IntArray,
    ): Int = gate(sql).let { delegate.executeUpdate(sql, columnIndexes) }

    override fun executeUpdate(
        sql: String,
        columnNames: Array<out String>,
    ): Int = gate(sql).let { delegate.executeUpdate(sql, columnNames) }

    override fun executeLargeUpdate(sql: String): Long = gate(sql).let { delegate.executeLargeUpdate(sql) }

    override fun executeLargeUpdate(
        sql: String,
        autoGeneratedKeys: Int,
    ): Long = gate(sql).let { delegate.executeLargeUpdate(sql, autoGeneratedKeys) }

    override fun executeLargeUpdate(
        sql: String,
        columnIndexes: IntArray,
    ): Long = gate(sql).let { delegate.executeLargeUpdate(sql, columnIndexes) }

    override fun executeLargeUpdate(
        sql: String,
        columnNames: Array<out String>,
    ): Long = gate(sql).let { delegate.executeLargeUpdate(sql, columnNames) }

    override fun addBatch(sql: String) = gate(sql).let { delegate.addBatch(sql) }

    override fun getConnection(): Connection = connection

    override fun <T : Any?> unwrap(iface: Class<T>): T =
        if (iface.isInstance(this)) iface.cast(this) else throw SQLException("a DuckDB staging author statement does not unwrap")

    override fun isWrapperFor(iface: Class<*>): Boolean = iface.isInstance(this)
}

/**
 * A prepared statement: its own text was gated at prepare time; the inherited `Statement` entry
 * points that take NEW text are gated here (JDBC forbids them on a prepared statement, but the gate
 * does not rely on a driver honouring that).
 */
internal class GuardedPreparedStatement(
    private val delegate: PreparedStatement,
    private val connection: Connection,
) : PreparedStatement by delegate {
    override fun execute(sql: String): Boolean = gate(sql).let { delegate.execute(sql) }

    override fun execute(
        sql: String,
        autoGeneratedKeys: Int,
    ): Boolean = gate(sql).let { delegate.execute(sql, autoGeneratedKeys) }

    override fun execute(
        sql: String,
        columnIndexes: IntArray,
    ): Boolean = gate(sql).let { delegate.execute(sql, columnIndexes) }

    override fun execute(
        sql: String,
        columnNames: Array<out String>,
    ): Boolean = gate(sql).let { delegate.execute(sql, columnNames) }

    override fun executeQuery(sql: String): ResultSet = gate(sql).let { delegate.executeQuery(sql) }

    override fun executeUpdate(sql: String): Int = gate(sql).let { delegate.executeUpdate(sql) }

    override fun executeUpdate(
        sql: String,
        autoGeneratedKeys: Int,
    ): Int = gate(sql).let { delegate.executeUpdate(sql, autoGeneratedKeys) }

    override fun executeUpdate(
        sql: String,
        columnIndexes: IntArray,
