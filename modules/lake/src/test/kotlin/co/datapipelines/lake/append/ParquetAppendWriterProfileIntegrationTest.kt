/**
 * P10 (brief 956 D9; record call 35): the append writer follows the table's profile, read at each append. Two tables
 * on profiles whose targets (16 MiB, 64 MiB) and row groups (256 KiB, 1 MiB) differ four-fold get the same rows
 * through the production runner, which reads `LakeProfiles.forTable` at the start of each append; then one profile is
 * edited and the other table reassigned, each followed by an append with no restart. Every profile is created, edited
 * and assigned through `LakeProfiles` (the production validator); no profile row is written by test SQL.
 *
 * The fixture: an unpartitioned table of a required BIGINT `id` and a BINARY `payload` of four MD5 digests (64 bytes
 * that zstd cannot shrink), generated by DuckDB at run time, nothing kept in the repository. A row is at most
 * [ROW_BYTES] bytes in a data page: 8 for the id, 4 for the binary's length prefix, 64 for the payload.
 *
 * The tolerances, from the pinned writer (Iceberg 1.12.0) and that width:
 * - a file rolls only when `BaseRollingWriter` checks, every 1,000 rows, that its length (bytes written plus the open
 *   row group's buffer) reached the target. A rolled file therefore ends at most 1,000 rows plus one row group past the
 *   target, and the length it rolled at can exceed the final size by at most that open row group's buffer. So every file
 *   but the last of an append lies within [fileTolerance] = 1,000 × [ROW_BYTES] + the row group size of its target.
 * - Iceberg's `ParquetWriter` flushes a row group when its buffered size comes within two average records of the target,
 *   checking at least every 100 and at most every 10,000 rows on an estimate that converges as the group fills. The
 *   footer records the group's COMPRESSED size, and the buffered size counts the sequential `id` at 8 of a row's 76
 *   bytes, which zstd stores in almost nothing: a full group is stored about 8/76 (10.5 %) below the size it flushed
 *   at. Every row group but the last of a file therefore lies within [rowGroupTolerance] = the bytes of 100 rows + a
 *   fifth of the target. Measured on 2026-11-14 (the `P10 measured` line, copied into the lane's handback): full groups
 *   at 0.87 – 0.92 of their target (256 KiB: 233,365 – 239,985; 1 MiB: 914,464 – 927,376; 512 KiB: 460,310 – 468,657;
 *   128 KiB: 120,018 – 125,863) and rolled files 28 – 125 KB past theirs, each inside its tolerance.
 */
class ParquetAppendWriterProfileIntegrationTest {
    private val h = AppendPublicationHarness(renewInterval = RENEW_INTERVAL)

    /** Each append is its own delivery (the ledger keys one by table, feed and id). */
    private var appends = 0

    @BeforeEach
    fun reset() {
        h.reset(BODY)
        h.addTable(OTHER, BODY)
    }

    @Test
    fun `the files and row groups follow each table's profile, and an edit or a reassignment applies at the next append`() {
        val started = System.nanoTime()
        h.profiles.create("p10_small", LakeProfileFixtures.sizes(16 * MIB, 256 * KIB), h.h.actor)
        h.profiles.create("p10_large", LakeProfileFixtures.sizes(64 * MIB, MIB), h.h.actor)
        h.profiles.assign(h.managedId(SMALL), "p10_small", h.h.actor)
        h.profiles.assign(h.managedId(OTHER), "p10_large", h.h.actor)
        val measured = mutableListOf<String>()
        LakeMinio.client().use { client ->
            // ONE runner (one writer) for every append, as the production bean: an edit applies with no restart.
            val runner = h.runner(client)
            val small = append(runner, SMALL, FIRST_ROWS)
            val large = append(runner, OTHER, FIRST_ROWS)
            measured += small.check("small", 16 * MIB, 256 * KIB)
            measured += large.check("large", 64 * MIB, MIB)
            withClue("the same rows, four-fold different targets: the file counts differ") { small.files.size shouldNotBe large.files.size }
            withClue("the row group counts differ") { small.rowGroups.sumOf { it.size } shouldNotBe large.rowGroups.sumOf { it.size } }

            h.profiles.edit("p10_small", LakeProfileFixtures.sizes(32 * MIB, 512 * KIB), h.h.actor)
            measured += append(runner, SMALL, EDIT_ROWS).check("edited", 32 * MIB, 512 * KIB)

            h.profiles.create("p10_reassigned", LakeProfileFixtures.sizes(16 * MIB, 128 * KIB), h.h.actor)
            h.profiles.assign(h.managedId(OTHER), "p10_reassigned", h.h.actor)
            measured += append(runner, OTHER, REASSIGN_ROWS).check("reassigned", 16 * MIB, 128 * KIB)
        }
        val seconds = Duration.ofNanos(System.nanoTime() - started).toSeconds()
        println("P10 measured: run ${seconds}s; " + measured.joinToString("; "))
    }

    /** One append of [rows] fixture rows to `publish799.<table>` through [runner]; the files its snapshot added. */
    private fun append(
        runner: LakeWritebackRunner,
        table: String,
        rows: Long,
    ): Appended {
        appends++
        h.withRequest(sql = sql(rows), table = table, deadline = APPEND_DEADLINE, deliveryId = "p10-$appends") { request, _ ->
            runner.publish(request) {}
        }
        return h.withTable(table) { iceberg ->
            val files =
                SnapshotChanges
                    .builderFor(iceberg)
                    .snapshot(iceberg.currentSnapshot())
                    .build()
                    .addedDataFiles()
                    .toList()
            files.sumOf { it.recordCount() } shouldBe rows
            Appended(files, files.map { rowGroupSizes(iceberg, it) })
        }
    }

    private data class Appended(
        val files: List<DataFile>,
        val rowGroups: List<List<Long>>,
    ) {
        /** Asserts every file but the last within the file tolerance and every row group but a file's last within its own. */
        fun check(
            label: String,
            target: Long,
            rowGroup: Long,
        ): String {
            // The snapshot does not keep the roll order. The append's last file is the remainder: dropping the smallest
            // file drops it, or drops a rolled file while keeping a remainder at least that large, which then lies
            // within the same bounds.
            val rolled = files.map { it.fileSizeInBytes() }.sorted().drop(1)
            val groups = rowGroups.flatMap { it.dropLast(1) }
            withClue("$label: at least two rolled files, so the file assertion is not vacuous") { (rolled.size >= 2) shouldBe true }
            withClue("$label: full row groups exist") { (groups.size >= 2) shouldBe true }
            assertSoftly {
                rolled.forEach { size ->
                    withClue("$label: a rolled file of $size bytes against the target $target") {
                        size shouldBeGreaterThanOrEqualTo target - fileTolerance(rowGroup)
                        size shouldBeLessThanOrEqualTo target + fileTolerance(rowGroup)
                    }
                }
                groups.forEach { size ->
                    withClue("$label: a full row group of $size bytes against $rowGroup") {
                        size shouldBeGreaterThanOrEqualTo rowGroup - rowGroupTolerance(rowGroup)
                        size shouldBeLessThanOrEqualTo rowGroup + rowGroupTolerance(rowGroup)
                    }
                }
            }
            return "$label target=$target files=${files.size} rolled=[${rolled.min()}..${rolled.max()}] " +
                "rowGroup=$rowGroup groups=${groups.size} full=[${groups.min()}..${groups.max()}]"
        }
    }

    /** The compressed size of each row group, from the footer read by two ranged reads (never the whole file). */
    private fun rowGroupSizes(
        table: Table,
        file: DataFile,
    ): List<Long> =
        table.io().newInputFile(file.location()).newStream().use { stream ->
            val length = file.fileSizeInBytes()
            stream.seek(length - TRAILER_BYTES)
            val footerLength = ByteBuffer.wrap(stream.readNBytes(Int.SIZE_BYTES)).order(ByteOrder.LITTLE_ENDIAN).int
            stream.seek(length - TRAILER_BYTES - footerLength)
            val footer = Util.readFileMetaData(ByteArrayInputStream(stream.readNBytes(footerLength)))
            footer.row_groups.map { group ->
                if (group.isSetTotal_compressed_size) {
                    group.total_compressed_size
                } else {
                    group.columns.sumOf { it.meta_data.total_compressed_size }
                }
            }
        }

    private companion object {
        const val KIB = 1024L
        const val MIB = 1024L * KIB
        const val SMALL = AppendPublicationHarness.TABLE
        const val OTHER = "returns"

        /** About 217 MiB at [ROW_BYTES]: at least three rolled files at 64 MiB. */
        const val FIRST_ROWS = 3_000_000L

        /** About 108 MiB: three rolled files at 32 MiB. */
        const val EDIT_ROWS = 1_500_000L

        /** About 72 MiB: four rolled files at 16 MiB. */
        const val REASSIGN_ROWS = 1_000_000L
        const val ROW_BYTES = 8L + 4L + 64L
        const val ROWS_PER_ROLL_CHECK = 1_000L
        const val ROWS_PER_MIN_GROUP_CHECK = 100L
        const val GROUP_SHARE_DIVISOR = 5L
        const val TRAILER_BYTES = 8L
        val APPEND_DEADLINE: Duration = Duration.ofMinutes(10)

        /** The stand-in heartbeat renews at most once a second, not at each of millions of rows (one UPDATE each). */
        val RENEW_INTERVAL: Duration = Duration.ofSeconds(1)

        val BODY = body(listOf(field(1, "id", "BIGINTEGER", "required" to true), field(2, "payload", "BINARY", "required" to true)))

        fun fileTolerance(rowGroup: Long): Long = ROWS_PER_ROLL_CHECK * ROW_BYTES + rowGroup

        fun rowGroupTolerance(rowGroup: Long): Long = ROWS_PER_MIN_GROUP_CHECK * ROW_BYTES + rowGroup / GROUP_SHARE_DIVISOR

        fun sql(rows: Long): String =
            "SELECT i::BIGINT AS id, unhex(md5('a' || i) || md5('b' || i) || md5('c' || i) || md5('d' || i)) AS payload " +
                "FROM range($rows) t(i)"
    }
}
