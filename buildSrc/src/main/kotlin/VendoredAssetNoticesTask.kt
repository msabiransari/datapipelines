import groovy.json.JsonSlurper
import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/** Generates browser-asset notices entirely from committed inputs, without dependency resolution. */
abstract class VendoredAssetNoticesTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val manifest: RegularFileProperty

    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val vendorDirectory: DirectoryProperty

    @get:Input abstract val firstParty: ListProperty<String>

    @get:OutputDirectory abstract val outputDirectory: DirectoryProperty

    init {
        group = "documentation"
        description = "Generates THIRD-PARTY-NOTICES.txt for vendored browser assets, offline."
    }

    @TaskAction
    fun generate() {
        val vendor =
            vendorDirectory
                .get()
                .asFile
                .toPath()
                .toRealPath()
        val report =
            VendoredAssetNotices.render(manifest.get().asFile.readText(), firstParty.get().toSet()) { path ->
                val file = vendor.resolve(path.removePrefix("vendor/")).normalize().toFile()
                check(file.toPath().startsWith(vendor) && (!file.exists() || file.toPath().toRealPath().startsWith(vendor))) {
                    "Licence path escapes vendor directory: $path"
                }
                if (file.isFile) file.readText(Charsets.UTF_8) else null
            }
        val output = outputDirectory.file("THIRD-PARTY-NOTICES.txt").get().asFile
        output.parentFile.mkdirs()
        output.writeText(report, Charsets.UTF_8)
    }
}

/** Deterministic inventory and verbatim upstream licence sections, shared with offline fixture tests. */
object VendoredAssetNotices {
    // Intended adopters: JS libraries (MIT), lucide (ISC), htmx (0BSD), fonts (OFL-1.1); #693.
    private val phrases =
        mapOf(
            "MIT" to listOf("Permission is hereby granted, free of charge"),
            "ISC" to listOf("Permission to use, copy, modify, and/or distribute", "provided that the above copyright notice"),
            "0BSD" to listOf("Permission to use, copy, modify, and/or distribute"),
            "OFL-1.1" to listOf("SIL OPEN FONT LICENSE Version 1.1"),
        )

    private data class Asset(
        val name: String,
        val license: String,
        val row: String,
        val text: String,
    )

    /** Missing coverage, unrecognised terms, mismatched text and stale allowances fail closed. */
    fun render(
        manifestJson: String,
        firstParty: Set<String>,
        licenceText: (String) -> String?,
    ): String {
        val manifest = JsonSlurper().parseText(manifestJson) as? Map<*, *> ?: error("Vendor manifest must be an object")
        val staleOwn = firstParty.filterNot { manifest.containsKey(it) }
        check(staleOwn.isEmpty()) { "STALE first-party blocks: ${staleOwn.sorted()}" }
        val assets =
            manifest.entries
                .filter { it.key !in firstParty }
                .map { (key, value) ->
                    val name = key as? String ?: error("Vendor block name must be a string")
                    val block = value as? Map<*, *> ?: error("Invalid vendor block: $name")
                    asset(name, block, licenceText)
                }.sortedBy { it.name }
        val stale = phrases.keys - assets.map { it.license }.toSet()
        check(stale.isEmpty()) { "STALE vendored licence allowlist entries (matched no block): ${stale.sorted()}" }
        return buildString {
            append("Datapipelines — THIRD-PARTY-NOTICES\nProduct code: AGPL-3.0 (see LICENSE).\n")
            append("Generated by :modules:web:generateVendoredAssetNotices; do not edit.\n")
            append("Scope: third-party browser-asset blocks in vendor/design-system/vendor-manifest.json.\n")
            append("Own code (no third-party licence requirement): ${firstParty.sorted().joinToString(", ")}\n\n")
            assets.forEach { append(it.row).append('\n') }
            assets.forEach {
                append("\n===== ${it.name} (${it.license}) =====\n")
                append(it.text).append('\n')
            }
        }
    }

    private fun asset(
        name: String,
        block: Map<*, *>,
        licenceText: (String) -> String?,
    ): Asset {
        fun field(key: String): String =
            (block[key] as? String)?.takeIf { it.isNotBlank() } ?: error("Missing $key for vendored block $name")
        val license = field("license")
        val required = phrases[license] ?: error("Unknown licence $license for vendored block $name")
        val path = field("license_file")
        check(path.startsWith("vendor/") && path.split('/').none { it == ".." || it == "." || it.isEmpty() }) {
            "Invalid license_file for vendored block $name: $path"
        }
        val text = licenceText(path)?.replace("\r\n", "\n")?.trim()
        check(!text.isNullOrBlank()) { "Missing or blank licence text for vendored block $name: $path" }
        // Upstream OFL files use both line wrapping and mixed case; preserve the original section bytes.
        val words = text.replace(Regex("\\s+"), " ")
        check(required.all { words.contains(it, ignoreCase = true) }) { "Wrong licence text for vendored block $name: expected $license" }
        val label = (block["package"] as? String)?.takeIf { it.isNotBlank() } ?: name
        return Asset(name, license, "$name — $label ${field("version")} — $license — ${field("source")}", text)
    }
}
