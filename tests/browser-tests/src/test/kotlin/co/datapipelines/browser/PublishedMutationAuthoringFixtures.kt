package co.datapipelines.browser

import com.microsoft.playwright.Page
import io.kotest.assertions.withClue
import io.kotest.matchers.shouldBe
import java.net.URI
import java.net.http.HttpClient
import java.net.http.HttpRequest
import java.net.http.HttpResponse
import java.sql.DriverManager
import java.time.Duration

/**
 * [PublishedMutationAuthoringBrowserTest]'s own fixtures (owner ruling 2026-11-08: one browser class per family, its
 * fixtures in its own helper). Seeding goes through the product's REST and form routes from inside the signed-in page
 * (session cookie + the CSRF header) — the ApiVersionsFixtures pattern; the CALLER of the published routes is an
 * external `java.net.http` client against the application's own listener, the supported ingress (no proxy is bundled).
 *
 * The write target is a scratch database of the suite's shared Postgres server, registered as a POSTGRES datasource
 * with the #933 pool fields; its tables are this class's alone.
 */
class PublishedMutationAuthoringFixtures(
    private val page: Page,
    private val baseUrl: String,
    suffix: String,
) {
    val database = "pm1040_$suffix"
    val datasource = "pm1040-$suffix"
    private val targetUrl = SharedBrowserE2e.jdbcUrl.substringBefore("?").substringBeforeLast("/") + "/$database"
    private val client: HttpClient = HttpClient.newBuilder().version(HttpClient.Version.HTTP_1_1).build()

    /** Creates the scratch database and its tables, and registers it as this workspace's datasource. */
    fun seedTarget() {
        val admin = SharedBrowserE2e.jdbcUrl
        DriverManager.getConnection(admin, SharedBrowserE2e.username, SharedBrowserE2e.password).use { c ->
            c.createStatement().use { it.execute("""CREATE DATABASE "$database"""") }
        }
        targetSql(
            "CREATE TABLE pm_lines (line_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sku text NOT NULL, " +
                "qty int NOT NULL, ext_id text, ext_number text)",
            "CREATE TABLE pm_tombstones (line_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sku text NOT NULL, " +
                "qty int NOT NULL, ext_id text, ext_number text)",
            "CREATE TABLE pm_state (name text PRIMARY KEY, state text NOT NULL)",
            "INSERT INTO pm_state (name, state) VALUES ('put-target', 'initial'), ('delete-target', 'present')",
        )
        val form =
            mapOf(
                "name" to datasource,
                "displayName" to "Mutation authoring target",
                "dialect" to "POSTGRES",
                "jdbcUrl" to targetUrl,
                "credentialKind" to "password",
                "username" to SharedBrowserE2e.username,
                "password" to SharedBrowserE2e.password,
                "description" to "#1040 browser write target",
            ) + SharedBrowserE2e.SOURCE_DATASOURCE_POOL_FIELDS
        withClue("datasource registration") { send("POST", "/partials/datasources", form = form).first shouldBe 200 }
    }

    /** One count over the scratch database — the second client's view of what the routes wrote. */
    fun count(sql: String): Int =
        DriverManager.getConnection(targetUrl, SharedBrowserE2e.username, SharedBrowserE2e.password).use { c ->
            c.createStatement().use { s ->
                s.executeQuery(sql).use {
                    it.next()
                    it.getInt(1)
                }
            }
        }

    /** A released POSTGRES SQL template. */
    fun sqlTemplate(
        id: String,
        sql: String,
    ) = releaseTemplate(
        id,
        """{"id":"$id","dialect":"POSTGRES","display_name":"$id","description":"#1040 fixture","imports":[],"body":${json(sql)}}""",
    )

    /** The released JSONata transformer that turns the request body (one line, or `lines`) into order rows. */
    fun linesTemplate(id: String) =
        releaseTemplate(
            id,
            """{"id":"$id","display_name":"$id","description":"#1040 body transformer","type":"jsonata",""" +
                """"body":${json(LINES_JSONATA)},"contract":$LINES_CONTRACT,"invariants":[],""" +
                """"tests":[{"name":"quiet","input":{"inputs":{"order":{}}},"expect":{"output":[]}}]}""",
        )

    /** Creates [name] from [nodes] (with [requestBody] when declared) and releases its v1. */
    fun pipeline(
        name: String,
        nodes: String,
        requestBody: String? = null,
    ) {
        val declared = requestBody?.let { ""","request_body":$it""" }.orEmpty()
        val (status, body) =
            send(
                "POST",
                "/api/v1/pipelines",
                """{"name":"$name","display_name":"${name.substringAfterLast('/')}","description":"#1040 fixture",""" +
                    """"parameters":{},"nodes":$nodes$declared}""",
            )
        withClue("create $name: $body") { status shouldBe 201 }
        val id = idOf(body)
        val hash = hashOf(send("GET", "/api/v1/pipelines/$id"))
        send("POST", "/api/v1/pipelines/$id/release", ifMatch = hash).first shouldBe 200
    }

    /** Publishes [method] [path] over [pipeline]@1 (v1 a DRAFT, authoring-enabled); the entity id. */
    fun publish(
        path: String,
        method: String,
        pipeline: String,
        timeoutSeconds: Int = TIMEOUT_S,
    ): String {
        val (status, body) =
            send(
                "POST",
                "/api/v1/endpoints",
                """{"path":"$path","method":"$method","pipeline":"$pipeline","pipeline_version":1,"timeout_seconds":$timeoutSeconds}""",
            )
        withClue("publish $method $path: $body") { status shouldBe 201 }
        return idOf(body)
    }

    /** Releases the entity's v1 through the REST route (the routes the browser does not walk). */
    fun releaseOverRest(entityId: String) {
        val hash = hashOf(send("GET", "/api/v1/endpoints/$entityId/versions/1"))
        send("POST", "/api/v1/endpoints/$entityId/release", ifMatch = hash).first shouldBe 200
    }

    /** One call from the external client: [credential] in `DP-API-Key`, an `Idempotency-Key` when given. */
    fun call(
        credential: String,
        method: String,
        path: String,
        idempotencyKey: String? = null,
        body: HttpRequest.BodyPublisher = HttpRequest.BodyPublishers.noBody(),
        json: Boolean = false,
    ): HttpResponse<String> {
        val request =
            HttpRequest
                .newBuilder(URI.create("$baseUrl$path"))
                .timeout(Duration.ofSeconds(CLIENT_TIMEOUT_S))
                .header("DP-API-Key", credential)
                .method(method, body)
        idempotencyKey?.let { request.header("Idempotency-Key", it) }
        if (json) request.header("Content-Type", "application/json")
        return client.send(request.build(), HttpResponse.BodyHandlers.ofString())
    }

    private fun releaseTemplate(
        id: String,
        payload: String,
    ) {
        val (status, body) = send("POST", "/api/v1/templates", payload)
        withClue("template $id: $body") { status shouldBe 201 }
        send("POST", "/api/v1/templates/release", """{"name":"$id"}""", ifMatch = hashOf(200 to body)).first shouldBe 200
    }

    private fun targetSql(vararg statements: String) =
        DriverManager.getConnection(targetUrl, SharedBrowserE2e.username, SharedBrowserE2e.password).use { c ->
            c.createStatement().use { s -> statements.forEach { s.execute(it) } }
        }

    private fun idOf(body: String?): String =
        requireNotNull(Regex(""""id"\s*:\s*"([0-9a-f-]+)"""").find(requireNotNull(body))).groupValues[1]

    private fun hashOf(response: Pair<Int, String?>): String {
        response.first shouldBe 200
        return requireNotNull(Regex(""""body_hash"\s*:\s*"([0-9a-f]+)"""").find(requireNotNull(response.second))).groupValues[1]
    }

    /** A JSON string literal of [text]. */
    private fun json(text: String): String = "\"" + text.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n") + "\""

    @Suppress("UNCHECKED_CAST")
    private fun send(
        method: String,
        url: String,
        body: String? = null,
        ifMatch: String? = null,
        form: Map<String, String>? = null,
    ): Pair<Int, String?> {
        val result =
            page.evaluate(
                """async (args) => {
                  const csrf = document.cookie.match(/(?:^|;\s*)dp_csrf=([^;]*)/);
                  const headers = {'DP-CSRF-Token': csrf ? decodeURIComponent(csrf[1]) : ''};
                  let payload = args.body ?? undefined;
                  if (args.form) {
                    headers['Content-Type'] = 'application/x-www-form-urlencoded';
                    payload = new URLSearchParams(args.form);
                  } else {
                    headers['Content-Type'] = 'application/json';
                  }
                  if (args.ifMatch) headers['If-Match'] = args.ifMatch;
                  const res = await fetch(args.url, {method: args.method, credentials: 'same-origin', headers, body: payload});
                  const text = await res.text();
                  return {status: res.status, body: text.length < 8192 ? text : null};
               }""",
                mapOf("method" to method, "url" to url, "body" to body, "ifMatch" to ifMatch, "form" to form),
            ) as Map<String, Any?>
        return (result["status"] as Number).toInt() to (result["body"] as String?)
    }

    companion object {
        const val TIMEOUT_S = 60
        const val CLIENT_TIMEOUT_S = 60L

        private const val LINES_JSONATA =
            "(\$o := inputs.order;\n" +
                " \$items := \$exists(\$o.lines) ? \$o.lines : (\$exists(\$o.sku) ? [\$o] : []);\n" +
                " [\$items.{\"sku\": sku, \"qty\": qty, \"ext_id\": null, \"ext_number\": null}])"

        private const val LINES_CONTRACT =
            """{"mode":"table","rejects":false,"inputs":{"order":{"kind":"body"}},"output":{"kind":"table","columns":[""" +
                """{"name":"sku","type":"STRING"},{"name":"qty","type":"INTEGER"},""" +
                """{"name":"ext_id","type":"STRING","nullable":true},{"name":"ext_number","type":"STRING","nullable":true}]}}"""
    }
}
